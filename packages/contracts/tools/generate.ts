import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { z } from 'zod';
import { CONTRACT_API_MAJOR, CONTRACT_VERSION, wireSchemas } from '../src/schemas.ts';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
if (args.some(arg => arg !== '--check')) throw new Error('Only --check is supported');
const check = args.includes('--check');
const digest = (text: string) => createHash('sha256').update(text).digest('hex');
const canonical = (value: unknown): string => JSON.stringify(value, (_key, current: unknown) => {
  if (current && typeof current === 'object' && !Array.isArray(current)) return Object.fromEntries(Object.entries(current).sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0));
  return current;
}, 2) + '\n';
const uri = `urn:personal-agent:contracts:${CONTRACT_VERSION}`;
const registry = z.registry<{ id: string }>();
for (const [name, schema] of Object.entries(wireSchemas) as [string, z.ZodType][]) schema.register(registry, { id: name });
const exported = z.toJSONSchema(registry, { target: 'draft-2020-12', io: 'input', uri: name => `${uri}:${name}` });
const document = { $schema: 'https://json-schema.org/draft/2020-12/schema', $id: uri, $defs: exported.schemas, 'x-api-major': CONTRACT_API_MAJOR, 'x-runtime-validation': 'Use the package Zod parsers for cross-field, registration and contextual answer rules.' };
const schemaText = canonical(document);
const sourceFiles = ['src/schemas.ts', 'src/validation.ts', 'src/ports.ts'];
const sourceHashes = Object.fromEntries(sourceFiles.map(path => [path, digest(readFileSync(resolve(root, path), 'utf8'))]));
const schemaHash = digest(canonical({ apiMajor: CONTRACT_API_MAJOR, version: CONTRACT_VERSION, jsonSchemaDigest: digest(schemaText), sourceHashes }));
const outputs = new Map<string, string>([
  ['generated/contracts.schema.json', schemaText],
  ['generated/manifest.json', canonical({ apiMajor: CONTRACT_API_MAJOR, version: CONTRACT_VERSION, schemaHash, jsonSchemaDigest: digest(schemaText), schemaNames: Object.keys(wireSchemas).sort(), sourceHashes, generator: 'zod@4.4.3 / JSON Schema 2020-12', runtimeValidationRequired: true })],
  ['src/types.ts', '// Generated by tools/generate.ts. Do not edit.\nimport type { z } from \'zod\';\nimport type { wireSchemas } from \'./schemas.ts\';\n\n' + Object.keys(wireSchemas).sort().map(name => `export type ${name} = z.infer<(typeof wireSchemas)['${name}']>;`).join('\n') + '\n'],
  ['src/identity.ts', `// Generated by tools/generate.ts. Do not edit.\nexport const CONTRACT_IDENTITY = ${JSON.stringify({ apiMajor: CONTRACT_API_MAJOR, version: CONTRACT_VERSION, schemaHash }, null, 2)} as const;\n`],
]);
for (const [path, content] of outputs) {
  const target = resolve(root, path);
  if (check) {
    if (readFileSync(target, 'utf8') !== content) throw new Error(`Generated artifact is stale: ${path}`);
  } else {
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, content);
  }
}
console.log(`${check ? 'Verified' : 'Generated'} ${Object.keys(wireSchemas).length} schemas; API ${CONTRACT_API_MAJOR}, ${CONTRACT_VERSION}, hash ${schemaHash}`);
